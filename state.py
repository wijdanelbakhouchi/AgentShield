from enum import Enum
from typing import Any, Dict, List, Optional, TypedDict
from pydantic import BaseModel, Field


class RiskLevel(str, Enum):
    """Canonical risk severity values emitted by every public endpoint."""

    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class Decision(str, Enum):
    """Canonical policy decisions shared by API, CLI, and graph callers."""

    ALLOW = "ALLOW"
    SANITIZE = "SANITIZE"
    REVIEW = "REVIEW"
    BLOCK = "BLOCK"


class TrustLevel(str, Enum):
    """Explicit provenance labels; execution success never grants trust."""

    TRUSTED_SYSTEM = "TRUSTED_SYSTEM"
    USER_CONTROLLED = "USER_CONTROLLED"
    EXTERNAL_UNTRUSTED = "EXTERNAL_UNTRUSTED"
    AGENT_GENERATED_UNTRUSTED = "AGENT_GENERATED_UNTRUSTED"
    INSPECTED_SAFE = "INSPECTED_SAFE"

    # Phase 4/7 compatibility aliases.  New boundaries must use the explicit
    # labels above, which distinguish raw external data from inspected data.
    USER_INPUT = USER_CONTROLLED
    USER_TASK = USER_CONTROLLED
    EXTERNAL_TOOL_DATA = EXTERNAL_UNTRUSTED
    EXTERNAL_INSPECTED_DATA = INSPECTED_SAFE
    AGENT_GENERATED = AGENT_GENERATED_UNTRUSTED
    AGENT_GENERATED_DATA = AGENT_GENERATED_UNTRUSTED
    SYSTEM_TRUSTED = TRUSTED_SYSTEM


class SecurityPayload(BaseModel):
    """Execution metadata and normalized payload produced by SecurityGateway."""

    request_id: str = Field(description="Unique UUID for the intercepted request")
    timestamp: str = Field(description="ISO format timestamp of interception")
    source: str = Field(
        description="Source of payload, e.g. user, research_agent, tools"
    )
    target: str = Field(
        description="Target agent or module, e.g. agent_orchestrator, planner_agent"
    )
    raw_input: str = Field(description="Original uncleaned raw input text")
    normalized_input: str = Field(description="Cleaned, standardized input text")
    normalization_metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Metadata emitted by the canonical input normalizer",
    )


class SecurityAnalysisResult(BaseModel):
    """Unified security evaluation result generated by RiskAnalyzer."""

    request_id: str = Field(description="Request ID associated with payload")
    timestamp: str = Field(description="Interception timestamp")
    normalized_input: str = Field(description="Normalized input string evaluated")
    rule_flags: List[str] = Field(
        default_factory=list, description="Triggered rule-based security flags"
    )
    llm_classification: Dict[str, Any] = Field(
        default_factory=dict,
        description="LLM semantic security classification result",
    )
    context_flags: List[str] = Field(
        default_factory=list,
        description="Flags detected in retrieved context/documents",
    )
    semantic_similarity: Dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "Real sentence-embedding evidence and runtime status. The finding "
            "is exposed for auditability and contributes through the calibrated "
            "semantic weight when its frozen detector threshold is met."
        ),
    )
    raw_signals: Dict[str, Any] = Field(
        default_factory=dict, description="Combined evidence signals from all detectors"
    )
    risk_score: float = Field(
        default=0.0,
        description="Aggregate security risk score between 0.0 (safe) and 1.0 (high threat)",
    )
    is_flagged: bool = Field(
        default=False, description="Whether the payload is flagged as a security threat"
    )


class RiskScoreResult(BaseModel):
    """Normalized risk score metrics generated by RiskScorer."""

    score: float = Field(ge=0.0, le=1.0, allow_inf_nan=False, description="Calculated composite risk score (0.0 to 1.0)")
    level: RiskLevel = Field(
        description="Risk severity level: LOW, MEDIUM, HIGH, or CRITICAL"
    )
    contributing_factors: List[str] = Field(
        default_factory=list,
        description="List of factors contributing to the risk score",
    )


class PolicyDecision(BaseModel):
    """Deterministic security enforcement decision generated by PolicyEngine."""

    action: Decision = Field(
        description="Enforcement action: ALLOW, SANITIZE, REVIEW, or BLOCK"
    )
    modified_input: Optional[str] = Field(
        default=None, description="Processed or sanitized input text for execution"
    )
    reason: str = Field(description="Explanation of the policy decision")
    risk_metrics: RiskScoreResult = Field(
        description="Risk scoring metrics evaluating the request"
    )


class SecurityPipelineResult(BaseModel):
    """Complete result returned by the canonical normalize-to-policy pipeline."""

    payload: SecurityPayload
    analysis: SecurityAnalysisResult
    risk: RiskScoreResult
    policy: PolicyDecision
    latency_ms: float = Field(description="Canonical security pipeline latency")


class UntrustedContent(BaseModel):
    """Server-created envelope for text received from an untrusted source."""

    content_id: str
    request_id: str
    source_type: str
    source_name: str
    text: str
    timestamp: str
    provenance: Dict[str, Any] = Field(default_factory=dict)
    trust_level: TrustLevel = TrustLevel.EXTERNAL_UNTRUSTED


class UntrustedContentSecurityResult(BaseModel):
    """Canonical policy disposition before untrusted text can reach an agent."""

    content_id: str
    request_id: str
    source_type: str
    source_name: str
    tool_execution_id: Optional[str] = None
    risk_score: float
    risk_level: RiskLevel
    decision: Decision
    findings: List[str] = Field(default_factory=list)
    transforms: List[str] = Field(default_factory=list)
    original_content: str
    safe_content: Optional[str] = None
    inspected: bool = True
    trust_level: TrustLevel = TrustLevel.EXTERNAL_UNTRUSTED
    timestamp: str
    latency_ms: float = 0.0
    reason: str = ""
    semantic_available: Optional[bool] = None


class AgentHandoff(BaseModel):
    """Server-created envelope for one untrusted agent-to-agent transition."""

    handoff_id: str = Field(description="Unique identifier for this transition")
    request_id: str = Field(description="Ingress request correlation identifier")
    source_agent: str = Field(description="Agent producing the outgoing payload")
    target_agent: str = Field(description="Agent that may consume the payload")
    content: str = Field(description="Original outgoing agent content")
    timestamp: str = Field(description="Timezone-aware UTC creation timestamp")
    content_type: str = Field(default="text", description="Logical payload type")
    trust_level: TrustLevel = Field(
        default=TrustLevel.AGENT_GENERATED,
        description="Origin classification; agent output is never trusted by default",
    )
    provenance: Dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "Message-level provenance summary of the handed-off content: "
            "message_id, origin chain, taint, propagation depth, attack id."
        ),
    )


class HandoffSecurityResult(BaseModel):
    """Canonical security disposition and safe forwarding value for a handoff."""

    request_id: str
    handoff_id: str
    source_agent: str
    target_agent: str
    risk_score: float
    risk_level: RiskLevel
    decision: Decision
    flags: List[str] = Field(default_factory=list)
    findings: List[str] = Field(default_factory=list)
    original_content: str
    safe_content: Optional[str] = None
    timestamp: str
    latency_ms: float = 0.0
    sanitized: bool = False
    blocked: bool = False
    reason: str = ""
    semantic_available: Optional[bool] = None
    provenance: Dict[str, Any] = Field(
        default_factory=dict,
        description="Provenance summary of the inspected handoff content.",
    )
    base_risk_score: Optional[float] = Field(
        default=None,
        description=(
            "Unadjusted canonical risk score before provenance-aware "
            "adjustment; equals risk_score when no adjustment was applied."
        ),
    )
    provenance_adjustment: Dict[str, Any] = Field(
        default_factory=dict,
        description="Auditable provenance risk adjustment record (see security.provenance).",
    )


class FinalOutputModel(BaseModel):
    """Structured Pydantic model for the final response format."""

    title: str = Field(description="Short title of the response")
    summary: str = Field(
        description="High-level summary of the findings and final response"
    )
    detailed_content: str = Field(
        description="Markdown-formatted detailed response body"
    )
    sources: List[str] = Field(
        default_factory=list, description="List of sources or tools referenced"
    )


class AgentState(TypedDict, total=False):
    """Shared state object passed between agent nodes in the LangGraph workflow."""

    user_query: str
    external_context: str
    research_data: str
    plan: str
    draft_response: str
    final_output: dict
    security_analysis: Optional[dict]
    policy_decision: Optional[dict]
    request_id: str
    security_context: Dict[str, Any]
    handoff_events: List[dict]
    handoff_results: List[dict]
    workflow_status: str
    blocked_at: str
    blocked_reason: str
    # Experiment-only switch used by the real baseline harness. Production
    # API requests omit it and therefore keep all guards enabled.
    security_enabled: bool
    attack_id: str
    # Phase 19 provenance-aware monitoring state.  ``provenance_by_field`` maps
    # each produced state field to its MessageProvenance summary; ``provenance_events``
    # keeps the ordered per-request provenance history for audit and evaluation.
    provenance_by_field: Dict[str, Any]
    provenance_events: List[dict]
    # Grounding & anti-hallucination state
    evidence_items: List[dict]
    rejected_evidence: List[dict]
    answer_validation: Dict[str, Any]
    # Final user-visible response disposition.  This is set only after the
    # finalizer has formatted the response and the independent output boundary
    # has scanned that exact text.
    output_security: Dict[str, Any]
